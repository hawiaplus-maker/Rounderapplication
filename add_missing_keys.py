for lang, translations in keys_translations.items():
    with open(f'assets/i18n/{lang}.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    for key, value in translations.items():
        data[key] = value

    # Write back with proper formatting
    with open(f'assets/i18n/{lang}.json', 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f'{lang}: added {len(translations)} keys')

